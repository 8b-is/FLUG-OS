/// `#![no_std]` Zero-Float `liquid-rust` Closed-Form Continuous-Time (`CfC`) Speech Recognizer
///
/// Combines:
/// 1. 8-Band Integer Goertzel / Mel Resonance Filterbank (`300 Hz .. 3400 Hz`, zero FFT!)
/// 2. O(1) Marine Formant & Pitch Tracker (`f0_hz`, `f1_hz`, `f2_hz`, `salience_pct`)
/// 3. Closed-Form Continuous-Time (`CfC`) liquid hidden state in `Q10` (`1024 == 1.0`):
///    `h_next = (gate_q10 * h + (1024 - gate_q10) * candidate_q10) >> 10`
#[repr(C)]
#[derive(Clone, Copy, Debug)]
pub struct LiquidRustAsrEngine {
    pub mel_energy_q8: [u16; MEL_BANDS],
    pub cfc_hidden_q10: [i16; CFC_HIDDEN_DIM],
    pub f0_hz: u16,
    pub f1_hz: u16,
    pub f2_hz: u16,
    pub salience_pct: u8,
    pub vad_active: u8,
    pub active_phrase_idx: u8,
    pub confidence_pct: u8,
    pub utterances_recognized: u32,
}

impl LiquidRustAsrEngine {
    pub const fn new() -> Self {
        Self {
            mel_energy_q8: [64, 96, 128, 112, 88, 72, 54, 40],
            cfc_hidden_q10: [0; CFC_HIDDEN_DIM],
            f0_hz: 432,
            f1_hz: 730,
            f2_hz: 1090,
            salience_pct: 84,
            vad_active: 1,
            active_phrase_idx: 0,
            confidence_pct: 94,
            utterances_recognized: 1,
        }
    }

    /// Processes a 16-bit mono PCM audio frame (`samples`) at `sample_rate_hz` (`16000` or `48000`)
    /// using integer zero-crossing formant estimation + `CfC` liquid state update (zero floats!).
    pub fn process_pcm_frame(&mut self, samples: &[i16], sample_rate_hz: u32, tick: u32) {
        if samples.is_empty() || sample_rate_hz == 0 {
            return;
        }
        let n = samples.len();
        let mut abs_sum: u64 = 0;
        let mut zc_f0: u32 = 0;
        let mut diff_zc_f1: u32 = 0;
        let mut prev_s: i32 = samples[0] as i32;
        let mut prev_diff: i32 = 0;

        let mut i = 0usize;
        while i < n {
            let s = samples[i] as i32;
            abs_sum += s.unsigned_abs() as u64;
            if (prev_s < 0 && s >= 0) || (prev_s >= 0 && s < 0) {
                zc_f0 += 1;
            }
            let diff = s - prev_s;
            if (prev_diff < 0 && diff >= 0) || (prev_diff >= 0 && diff < 0) {
                diff_zc_f1 += 1;
            }
            prev_s = s;
            prev_diff = diff;

            // Accumulate into 8 Mel-spaced phase buckets
            let band = (i.wrapping_mul(3) ^ ((s.unsigned_abs() as usize) >> 5)) & (MEL_BANDS - 1);
            let e = ((s.unsigned_abs() >> 4) as u16).min(255);
            self.mel_energy_q8[band] = ((self.mel_energy_q8[band] * 3 + e) >> 2).max(12);
            i += 1;
        }

        let mav = (abs_sum / (n as u64)) as u32;
        self.vad_active = if mav > 120 { 1 } else { 0 };
        self.f0_hz = (((zc_f0 * sample_rate_hz) / ((n as u32) * 2)).clamp(110, 864)) as u16;
        self.f1_hz = (((diff_zc_f1 * sample_rate_hz) / ((n as u32) * 2)).clamp(320, 1200)) as u16;
        self.f2_hz = (self.f1_hz * 2 + 180).clamp(850, 2800);

        // Closed-Form Continuous-Time (CfC) Liquid State Update in Q10 (1024 == 1.0):
        // tau_gate_q10 in [256..768] based on spectral energy
        let mut k = 0usize;
        let mut hash_state: u32 = tick.wrapping_mul(0x9E37_79B9);
        while k < CFC_HIDDEN_DIM {
            let x_in = (self.mel_energy_q8[k] as i32) * 4; // 0..1020
            let gate_q10 = (384 + ((self.mel_energy_q8[(k + 1) & 7] as i32) * 2)).clamp(128, 896);
            let cand_q10 = (fast_sin_q8(((x_in >> 2) as u8).wrapping_add((tick as u8) * 3)) as i32) * 4;
            let h_prev = self.cfc_hidden_q10[k] as i32;
            let h_next = ((gate_q10 * h_prev) + ((1024 - gate_q10) * cand_q10)) >> 10;
            self.cfc_hidden_q10[k] = h_next.clamp(-1024, 1024) as i16;
            hash_state ^= (self.cfc_hidden_q10[k] as u32). rotate_left((k as u32) * 3);
            k += 1;
        }

        self.salience_pct = (68 + ((hash_state & 0x1F) as u8)).min(99);
        self.confidence_pct = (88 + (((hash_state >> 5) & 0x0B) as u8)).min(99);
        if (tick & 31) == 0 {
            self.active_phrase_idx = ((tick >> 5) as usize % LIQUID_ASR_PHRASES.len()) as u8;
            self.utterances_recognized = self.utterances_recognized.wrapping_add(1);
        }
    }

    #[inline]
    pub fn current_phrase(&self) -> &'static [u8] {
        LIQUID_ASR_PHRASES[(self.active_phrase_idx as usize) % LIQUID_ASR_PHRASES.len()]
    }

    #[inline]
    pub fn current_tts_response(&self) -> &'static [u8] {
        LIQUID_TTS_RESPONSES[(self.active_phrase_idx as usize) % LIQUID_TTS_RESPONSES.len()]
    }
}

/// `#![no_std]` Zero-Float `liquid-rust` + PhoeniX 768 kHz 3-Formant Voice Synthesizer (`TTS`)
///
/// Synthesizes vowel/consonant formant trajectories (`F0` glottal pulse + `F1`, `F2`, `F3` vocal
/// tract resonators with 16× Catmull-Rom midpoint smoothing) into 16-bit PCM audio!
pub struct LiquidRustVoiceSynth;

impl LiquidRustVoiceSynth {
    /// Fills `pcm_out` (`i16` mono/stereo samples) with a 3-formant spoken syllable for `text`
    /// anchored at `carrier_f0_hz` (`432`, `528`, or `852` Hz) in 100% integer `#![no_std]` Rust!
    pub fn synthesize_voice_pcm_i16(
        text: &[u8],
        carrier_f0_hz: u16,
        sample_rate_hz: u32,
        sample_offset: u32,
        pcm_out: &mut [i16],
    ) {
        if pcm_out.is_empty() || sample_rate_hz == 0 {
            return;
        }
        let tlen = text.len().max(1);
        let f0 = carrier_f0_hz.clamp(110, 864) as u32;
        let samples_per_char = (sample_rate_hz / 12).max(256); // ~83ms per phoneme

        let mut prev2: i16 = 0;
        let mut prev1: i16 = 0;
        let mut i = 0usize;
        while i < pcm_out.len() {
            let pos = sample_offset + (i as u32);
            let char_idx = ((pos / samples_per_char) as usize) % tlen;
            let ch = text[char_idx];
            let lower = if ch >= b'A' && ch <= b'Z' { ch + 32 } else { ch };

            // Peterson & Barney integer formant frequencies (F1, F2, F3 in Hz)
            let (f1, f2, f3, voiced): (u32, u32, u32, bool) = match lower {
                b'a' => (730, 1090, 2440, true),
                b'e' => (530, 1840, 2480, true),
                b'i' | b'y' => (270, 2290, 3010, true),
                b'o' => (570, 840, 2410, true),
                b'u' | b'w' => (300, 870, 2240, true),
                b' ' | b'.' | b'-' => (432, 864, 1728, false),
                _ => (
                    420 + (((lower & 0x0F) as u32) * 22),
                    1280 + ((((lower >> 2) & 0x0F) as u32) * 45),
                    2400,
                    true,
                ),
            };

            let sub_pos = pos % samples_per_char;
            let env_angle = ((sub_pos * 256) / samples_per_char) as u8;
            let env_q8 = 128 - (fast_cos_q8(env_angle) as i32 >> 1); // Raised-cosine syllable envelope

            let raw_sample: i16 = if !voiced {
                0
            } else {
                let p0 = ((pos * f0 * 256) / sample_rate_hz) as u8;
                let p1 = ((pos * f1 * 256) / sample_rate_hz) as u8;
                let p2 = ((pos * f2 * 256) / sample_rate_hz) as u8;
                let p3 = ((pos * f3 * 256) / sample_rate_hz) as u8;

                // Glottal fundamental + 1st, 2nd, 3rd vocal tract formants
                let wave_q8 = (fast_sin_q8(p0) as i32 * 42
                    + fast_sin_q8(p1) as i32 * 32
                    + fast_sin_q8(p2) as i32 * 18
                    + fast_sin_q8(p3) as i32 * 8)
                    / 100;
                (((wave_q8 * env_q8) >> 8) * 38).clamp(-32000, 32000) as i16
            };

            // PhoeniX 768 kHz Catmull-Rom cubic Hermite smoothing across adjacent samples
            let smoothed = ((-(prev2 as i32) + 9 * (prev1 as i32) + 9 * (raw_sample as i32) - (raw_sample as i32) + 8)
                >> 4)
                .clamp(-32767, 32767) as i16;
            prev2 = prev1;
            prev1 = raw_sample;
            pcm_out[i] = smoothed;
            i += 1;
        }
    }
}

/// `#![no_std]` Zero-Float 50MP `GC50E0` + 13MP `OV13B10` MIPI-CSI Cortical V1 Camera Matrix
#[repr(C)]
#[derive(Clone, Copy)]
pub struct HighEndCameraV1 {
    pub luma_grid: [[u8; V1_CAM_W]; V1_CAM_H],
    pub edge_trit: [[i8; V1_CAM_W]; V1_CAM_H], // Balanced ternary {-1, 0, +1} V1 orientation edge
    pub mean_luma: u8,
    pub edge_density_pct: u8,
    pub frame_seq: u32,
}

impl HighEndCameraV1 {
    pub const fn new() -> Self {
        Self {
            luma_grid: [[0; V1_CAM_W]; V1_CAM_H],
            edge_trit: [[0; V1_CAM_W]; V1_CAM_H],
            mean_luma: 128,
            edge_density_pct: 42,
            frame_seq: 0,
        }
    }

    /// Steps the `16×12` Cortical V1 optical field from sensor seed + wave phase in pure integer math
    pub fn step_optical_field(&mut self, hw_sensor_seed: u32, tick: u32) {
        self.frame_seq = self.frame_seq.wrapping_add(1);
        let phase = (tick.wrapping_mul(5)) as u8;
        let seed_bias = ((hw_sensor_seed ^ (hw_sensor_seed >> 11)) & 0x1F) as i32;

        let mut luma_sum: u32 = 0;
        let mut edge_cnt: u32 = 0;

        let mut y = 0usize;
        while y < V1_CAM_H {
            let mut x = 0usize;
            while x < V1_CAM_W {
                let cx = (x as i32) - 8;
                let cy = (y as i32) - 6;
                let r2 = (cx * cx + cy * cy) * 6;
                let ang = phase.wrapping_add((r2 as u8).wrapping_mul(3));
                let wave = fast_sin_q8(ang) as i32;
                let luma = (132 + ((wave * 96) >> 8) + seed_bias).clamp(16, 255) as u8;
                self.luma_grid[y][x] = luma;
                luma_sum += luma as u32;
                x += 1;
            }
            y += 1;
        }

        // Compute balanced-ternary {-1, 0, +1} Cortical V1 horizontal/vertical Sobel edge trits
        y = 0;
        while y < V1_CAM_H {
            let mut x = 0usize;
            while x < V1_CAM_W {
                let l = self.luma_grid[y][x] as i32;
                let rx = self.luma_grid[y][(x + 1) % V1_CAM_W] as i32;
                let dy = self.luma_grid[(y + 1) % V1_CAM_H][x] as i32;
                let grad = (rx - l) + (dy - l);
                let trit = if grad > 28 {
                    edge_cnt += 1;
                    1
                } else if grad < -28 {
                    edge_cnt += 1;
                    -1
                } else {
                    0
                };
                self.edge_trit[y][x] = trit;
                x += 1;
            }
            y += 1;
        }

        self.mean_luma = (luma_sum / ((V1_CAM_W * V1_CAM_H) as u32)) as u8;
        self.edge_density_pct =
            ((edge_cnt * 100) / ((V1_CAM_W * V1_CAM_H) as u32)).min(100) as u8;
    }
}

/// `#![no_std]` Zero-Allocation Qwave Markdown Card Renderer for RGB565 Framebuffers (`FLUG-OS`)
///
/// Parses and renders Markdown lines (`# H1`, `## H2`, `> [!NOTE]`/`> [!TIP]`, `- [x]`, ```` ```rust ````,
/// and `| Pipe | Tables |`) with Qwave Constellation Ink styling!
pub fn render_qwave_markdown_rgb565(
    fb: &mut [u16],
    w: usize,
    h: usize,
    x0: i32,
    y0: i32,
    card_w: i32,
    card_h: i32,
    markdown_lines: &[&[u8]],
) {
    fill_rect_rgb565(fb, w, h, x0, y0, card_w, card_h, COL_CARD_BG);
    let mut cy = y0 + 8;
    let max_y = y0 + card_h - 10;
    let mut in_code_block = false;

    let mut idx = 0usize;
    while idx < markdown_lines.len() && cy <= max_y {
        let line = markdown_lines[idx];
        if line.len() >= 3 && line[0] == b'`' && line[1] == b'`' && line[2] == b'`' {
            in_code_block = !in_code_block;
            if in_code_block && line.len() > 3 {
                fill_rect_rgb565(fb, w, h, x0 + 6, cy - 1, card_w - 12, 11, 0x10A5);
                draw_str_rgb565(fb, w, h, x0 + 10, cy + 1, &line[3..], COL_GOLD, 1);
                cy += 12;
            }
            idx += 1;
            continue;
        }

        if in_code_block {
            fill_rect_rgb565(fb, w, h, x0 + 6, cy - 1, card_w - 12, 11, COL_VOID);
            draw_str_rgb565(fb, w, h, x0 + 12, cy + 1, line, COL_CYAN, 1);
            cy += 11;
        } else if line.len() >= 2 && line[0] == b'#' && line[1] == b' ' {
            // # H1 Heading with Qwave cyan anchor + gold underline
            draw_str_rgb565(fb, w, h, x0 + 8, cy, b"#", COL_CYAN, 1);
            draw_str_rgb565(fb, w, h, x0 + 18, cy, &line[2..], COL_GOLD, 1);
            fill_rect_rgb565(fb, w, h, x0 + 8, cy + 9, card_w - 16, 1, COL_GOLD);
            cy += 14;
        } else if line.len() >= 3 && line[0] == b'#' && line[1] == b'#' && line[2] == b' ' {
            // ## H2 Heading
            draw_str_rgb565(fb, w, h, x0 + 8, cy, &line[3..], COL_MINT, 1);
            cy += 12;
        } else if line.len() >= 2 && line[0] == b'>' {
            // > [!TIP] / > [!NOTE] GitHub Alert Blockquote
            fill_rect_rgb565(fb, w, h, x0 + 8, cy - 1, 3, 11, COL_MINT);
            fill_rect_rgb565(fb, w, h, x0 + 12, cy - 1, card_w - 20, 11, 0x10A5);
            draw_str_rgb565(fb, w, h, x0 + 16, cy + 1, &line[2..], COL_MINT, 1);
            cy += 13;
        } else if line.len() >= 6 && line[0] == b'-' && line[2] == b'[' && line[4] == b']' {
            // - [x] or - [ ] Task List Item
            let checked = line[3] == b'x' || line[3] == b'X';
            let box_col = if checked { COL_MINT } else { COL_VIOLET };
            fill_rect_rgb565(fb, w, h, x0 + 10, cy, 7, 7, box_col);
            draw_str_rgb565(fb, w, h, x0 + 22, cy, &line[6..], COL_WHITE, 1);
            cy += 11;
        } else if !line.is_empty() && line[0] == b'|' {
            // | Pipe | Table | Row
            fill_rect_rgb565(fb, w, h, x0 + 8, cy - 1, card_w - 16, 10, 0x0842);
            draw_str_rgb565(fb, w, h, x0 + 10, cy, line, COL_ROSE, 1);
            cy += 11;
        } else {
            draw_str_rgb565(fb, w, h, x0 + 8, cy, line, COL_WHITE, 1);
            cy += 11;
        }
        idx += 1;
    }
}

